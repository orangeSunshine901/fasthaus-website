// Pre-encode storefront mobile photos so the first visitor does not pay for an
// on-demand image transform. Original files and CMS media selections stay intact.
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import sharp from "sharp";
import { PRODUCTS } from "../lib/data/products.ts";
import { GALLERY_PORTRAITS } from "../lib/data/gallery-portraits.ts";

const root = new URL("../", import.meta.url);
const sources = new Set(
  PRODUCTS.flatMap((product) => product.variants.flatMap((variant) =>
    variant.images.map((image) => {
      const source = image.mobileSrc ?? image.src;
      return GALLERY_PORTRAITS[source] ?? source;
    })
  ))
);
const mapping = {};
const generatedNames = new Set();
let originalBytes = 0;
let mobileBytes = 0;
await mkdir(new URL("public/gallery-mobile/", root), { recursive: true });

for (const source of [...sources].sort()) {
  if (!/^\/[\w/.-]+\.(png|jpe?g|webp|avif)$/i.test(source)) continue;
  const input = await readFile(new URL(`public${source}`, root));
  const encode = (width, quality) => sharp(input).rotate()
    .resize({ width, withoutEnlargement: true })
    .webp({ quality, effort: 5 }).toBuffer();
  let output = await encode(1080, 86);
  for (const quality of [80, 74, 68]) {
    if (output.length <= 300 * 1024) break;
    output = await encode(1080, quality);
  }
  if (output.length > 300 * 1024) output = await encode(864, 80);
  const hash = createHash("sha256").update(output).digest("hex").slice(0, 10);
  const name = source.slice(1).replaceAll("/", "--").replace(/\.[^.]+$/, "");
  const destination = `/gallery-mobile/${name}-${hash}.webp`;
  generatedNames.add(`${name}-${hash}.webp`);
  await writeFile(new URL(`public${destination}`, root), output);
  mapping[source] = destination;
  originalBytes += input.length;
  mobileBytes += output.length;
}

// This directory contains only reproducible derivatives owned by this script.
for (const name of await readdir(new URL("public/gallery-mobile/", root))) {
  if (name.endsWith(".webp") && !generatedNames.has(name)) {
    await unlink(new URL(`public/gallery-mobile/${name}`, root));
  }
}

await writeFile(
  new URL("lib/data/mobile-gallery-images.ts", root),
  `// Generated by npm run images:mobile. Originals and crops are preserved.\nexport const MOBILE_GALLERY_IMAGES: Record<string, string> = ${JSON.stringify(mapping, null, 2)};\n`
);
console.log(JSON.stringify({ images: Object.keys(mapping).length, originalBytes, mobileBytes,
  reductionPercent: Math.round((1 - mobileBytes / originalBytes) * 100) }));
