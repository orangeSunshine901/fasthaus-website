// FilePond's canvas transforms run once in a local browser, never on the storefront.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const require = createRequire(import.meta.url);
const root = new URL("../", import.meta.url);
const crops = JSON.parse(await readFile(new URL("gallery-portrait-crops.json", import.meta.url)));
const browser = await chromium.launch({ channel: process.env.PORTRAIT_BROWSER || "chrome" });

try {
  const page = await browser.newPage();
  await page.route("**/*", (route) => route.abort());
  await page.setContent('<input type="file" id="images">');
  for (const name of ["filepond", "filepond-plugin-image-crop", "filepond-plugin-image-resize", "filepond-plugin-image-transform"]) {
    await page.addScriptTag({ path: require.resolve(`${name}/dist/${name}.js`) });
  }
  await page.evaluate(() => {
    window.FilePond.registerPlugin(
      window.FilePondPluginImageCrop,
      window.FilePondPluginImageResize,
      window.FilePondPluginImageTransform,
    );
    window.pond = window.FilePond.create(document.querySelector("#images"), {
      instantUpload: false,
      allowImageTransform: true,
      imageCropAspectRatio: "3:4",
      imageResizeTargetWidth: 1080,
      imageResizeTargetHeight: 1440,
      imageResizeMode: "contain",
      imageResizeUpscale: false,
      imageTransformOutputMimeType: "image/jpeg",
      imageTransformOutputQuality: 90,
    });
  });

  const mapping = {};
  await mkdir(new URL("public/gallery-portraits/", root), { recursive: true });
  for (const { src, center } of crops) {
    if (!/^\/[\w/-]+\.(png|jpe?g)$/.test(src)) throw new Error(`Invalid source: ${src}`);
    const bytes = await readFile(new URL(`public${src}`, root));
    const result = await page.evaluate(async ({ base64, src, center }) => {
      const blob = new Blob([Uint8Array.from(atob(base64), (char) => char.charCodeAt(0))], {
        type: src.endsWith(".png") ? "image/png" : "image/jpeg",
      });
      const original = await createImageBitmap(blob);
      if (original.width <= original.height) throw new Error(`Already portrait: ${src}`);
      original.close();
      const item = await window.pond.addFile(new File([blob], src.split("/").pop(), { type: blob.type }));
      item.setImageCropCenter(center);
      const { output } = await window.pond.prepareFile(item.id);
      const image = await createImageBitmap(output);
      const { width, height } = image;
      image.close();
      if (Math.abs(width / height - 3 / 4) > 0.002) throw new Error(`Invalid crop: ${width}x${height}`);
      const data = await new Promise((resolve, reject) => {
        const reader = new FileReader();
        reader.onload = () => resolve(reader.result.split(",")[1]);
        reader.onerror = reject;
        reader.readAsDataURL(output);
      });
      await window.pond.removeFile(item.id);
      return { data, width, height };
    }, { base64: bytes.toString("base64"), src, center });
    const destination = `/gallery-portraits/${src.slice(1).replaceAll("/", "--").replace(/\.[^.]+$/, ".jpg")}`;
    await writeFile(new URL(`public${destination}`, root), Buffer.from(result.data, "base64"));
    mapping[src] = destination;
    console.log(`${result.width}x${result.height} ${destination}`);
  }
  const manifest = new URL("lib/data/gallery-portraits.ts", root);
  await writeFile(manifest, `// Generated by npm run images:portraits. Edit crop centers in scripts/gallery-portrait-crops.json.\nexport const GALLERY_PORTRAITS: Record<string, string> = ${JSON.stringify(mapping, null, 2)};\n`);
  console.log(`Wrote ${Object.keys(mapping).length} mobile portrait crops and ${fileURLToPath(manifest)}`);
} finally {
  await browser.close();
}
